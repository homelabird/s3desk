import { expect, test } from '@playwright/test'

import { buildMetaFixture, buildObjectsListFixture, seedLocalStorage } from './support/apiFixtures'
import { installJobsMobileResponsiveFixtures, seedJobsMobileResponsiveStorage } from './support/jobsMobileResponsive'
import { installObjectsMobileResponsiveFixtures, seedObjectsMobileResponsiveStorage } from './support/objectsMobileResponsive'
import { installProfilesBucketsMobileResponsiveFixtures, seedProfilesBucketsMobileResponsiveStorage } from './support/profilesBucketsMobileResponsive'
import { installSettingsMobileResponsiveFixtures, seedSettingsMobileResponsiveStorage } from './support/settingsLoginMobileResponsive'
import { gotoJobsPage, gotoObjectsPage, gotoProfilesPage } from './support/ui'

for (const width of [390, 1280]) {
	test(`empty filtered results offer a working reset at ${width}px`, async ({ page }, testInfo) => {
		await page.setViewportSize({ width, height: 900 })
		await installObjectsMobileResponsiveFixtures(page)
		await seedObjectsMobileResponsiveStorage(page)
		await gotoObjectsPage(page)
		await expect(page.getByText('alpha.txt', { exact: true })).toBeVisible()
		await page.getByRole('button', { name: /Filters|View options/ }).click()
		const filters = page.getByRole('dialog', { name: 'View options', exact: true })
		await filters.getByLabel('Type filter', { exact: true }).selectOption('files')
		await filters.getByLabel('Extension filter', { exact: true }).fill('no-match')
		await filters.getByRole('button', { name: 'Done', exact: true }).click()
		await expect(page.getByText('No results', { exact: true })).toBeVisible()
		await page.screenshot({ path: testInfo.outputPath('empty-filtered-results.png'), animations: 'disabled' })
		await expect(page.getByRole('button', { name: 'Clear search', exact: true })).toHaveCount(0)
		const reset = page.getByRole('button', { name: 'Reset view', exact: true })
		await expect(reset).toBeEnabled()
		await page.getByRole('textbox', { name: 'Search current folder', exact: true }).fill('alpha')
		await page.getByRole('button', { name: 'Clear search', exact: true }).click()
		await expect(page.getByText('No results', { exact: true })).toBeVisible()
		await expect(reset).toBeEnabled()
		await reset.click()
		await expect(page.getByText('alpha.txt', { exact: true })).toBeVisible()
		await expect(page.getByText('No results', { exact: true })).toHaveCount(0)
		await page.getByRole('textbox', { name: 'Search current folder', exact: true }).fill('no-match')
		await expect(page.getByText('No results', { exact: true })).toBeVisible()
		await page.getByRole('button', { name: 'Clear search', exact: true }).click()
		await expect(page.getByText('alpha.txt', { exact: true })).toBeVisible()
	})

	test(`failed initial object load avoids an empty-folder claim and can retry at ${width}px`, async ({ page }, testInfo) => {
		test.setTimeout(45_000)
		await page.setViewportSize({ width, height: 900 })
		await installObjectsMobileResponsiveFixtures(page)
		await seedObjectsMobileResponsiveStorage(page)
		let failing = true
		await page.route('**/api/v1/buckets/objects-mobile-bucket/objects?**', async route => {
			if (!failing) return route.fallback()
			await route.fulfill({ status: 403, json: { error: { code: 'forbidden', message: 'Object listing denied.' } } })
		})
		await gotoObjectsPage(page)
		await expect(page.getByText('Object listing denied.', { exact: false })).toBeVisible({ timeout: 30_000 })
		await page.screenshot({ path: testInfo.outputPath('object-load-error.png'), animations: 'disabled' })
		await expect(page.getByText('Empty folder', { exact: true })).toHaveCount(0)
		await expect(page.getByText('No results', { exact: true })).toHaveCount(0)
		failing = false
		await page.getByRole('button', { name: /Retry/ }).click()
		await expect(page.getByText('alpha.txt', { exact: true })).toBeVisible()
	})

	test(`failed object refresh preserves loaded rows at ${width}px`, async ({ page }, testInfo) => {
		test.setTimeout(45_000)
		await page.setViewportSize({ width, height: 900 })
		await installObjectsMobileResponsiveFixtures(page)
		await seedObjectsMobileResponsiveStorage(page)
		await gotoObjectsPage(page)
		await expect(page.getByText('alpha.txt', { exact: true })).toBeVisible()
		await page.route('**/api/v1/buckets/objects-mobile-bucket/objects?**', route => route.fulfill({ status: 403, json: { error: { code: 'forbidden', message: 'Object refresh denied.' } } }))
		await page.getByRole('button', { name: /^(More actions|Object tools)$/ }).click()
		await page.getByRole('menuitem', { name: /Refresh/ }).click()
		await expect(page.getByText('Object refresh denied.', { exact: false })).toBeVisible({ timeout: 30_000 })
		await expect(page.getByText('alpha.txt', { exact: true })).toBeVisible()
		await expect(page.getByText('preview.png', { exact: true })).toBeVisible()
		await expect(page.getByText('Empty folder', { exact: true })).toHaveCount(0)
		await page.screenshot({ path: testInfo.outputPath('cached-object-refresh-error.png'), animations: 'disabled' })
	})
}

for (const width of [320, 1280]) {
	const themeMode = width === 320 ? 'light' : 'dark'
	test(`simple selection has one set of selection actions at ${width}px`, async ({ page }, testInfo) => {
		await page.setViewportSize({ width, height: 900 })
		await installObjectsMobileResponsiveFixtures(page)
		await seedObjectsMobileResponsiveStorage(page, { objectsUIMode: 'simple' })
		await seedLocalStorage(page, { themeMode })
		await gotoObjectsPage(page)
		await page.getByRole('checkbox', { name: 'Select alpha.txt', exact: true }).check()
		await expect(page.getByRole('button', { name: /^Download/ })).toHaveCount(1)
		await expect(page.getByRole('button', { name: /^Delete/ })).toHaveCount(1)
		await page.screenshot({ path: testInfo.outputPath('simple-selection.png'), animations: 'disabled' })
	})

	test(`invalid token feedback stays beside the input at ${width}px`, async ({ page }, testInfo) => {
		await page.setViewportSize({ width, height: 900 })
		await installSettingsMobileResponsiveFixtures(page)
		await seedSettingsMobileResponsiveStorage(page)
		await seedLocalStorage(page, { themeMode })
		await page.goto('/settings')
		const settings = page.getByRole('dialog', { name: 'Settings', exact: true })
		const token = settings.getByLabel('API token', { exact: true })
		await token.fill('invalid-한글')
		await settings.getByRole('button', { name: 'Apply', exact: true }).click()
		const error = settings.getByRole('alert').filter({ hasText: 'API token must use only ASCII or Latin-1 characters.' })
		await expect(error).toBeVisible()
		await expect(token).toHaveAttribute('aria-invalid', 'true')
		const wrapper = settings.locator('.ant-input-affix-wrapper').filter({ has: page.getByLabel('API token', { exact: true }) })
		await expect(wrapper).toHaveCSS('border-top-color', themeMode === 'light' ? 'rgb(185, 74, 67)' : 'rgb(220, 145, 141)')
		await expect(settings.getByText('Unapplied token change. Select Apply to reconnect.', { exact: true })).toHaveCount(0)
		await page.screenshot({ path: testInfo.outputPath('token-inline-error.png'), animations: 'disabled' })
		await token.fill('valid-draft')
		await expect(error).toHaveCount(0)
		await expect(token).not.toHaveAttribute('aria-invalid', 'true')
		await expect(settings.getByText('Unapplied token change. Select Apply to reconnect.', { exact: true })).toBeVisible()
	})

	test(`profile choice and saved TLS remain clear at ${width}px`, async ({ page }, testInfo) => {
		await page.setViewportSize({ width, height: 900 })
		await installProfilesBucketsMobileResponsiveFixtures(page)
		await seedProfilesBucketsMobileResponsiveStorage(page)
		await seedLocalStorage(page, { themeMode })
		const meta = buildMetaFixture()
		await page.route('**/api/v1/meta', route => route.fulfill({ json: { ...meta, capabilities: { ...meta.capabilities, profileTls: { enabled: true } } } }))
		await page.route('**/api/v1/profiles/profiles-buckets-mobile-profile/tls', route => route.fulfill({ json: { mode: 'mtls', hasClientCert: true, hasClientKey: true, hasCa: false } }))
		await gotoProfilesPage(page)
		const activeTools = page.getByRole('button', { name: 'Profile tools for Responsive Profile', exact: true })
		await expect(activeTools).toBeVisible()
		await expect(page.getByRole('button', { name: 'Selected', exact: true })).toHaveCount(0)
		await expect(page.getByRole('button', { name: /Use profile|^Use$/ })).toHaveCount(1)
		if (width === 320) {
			await expect(page.getByText('profiles-buckets-mobile-profile', { exact: true })).toHaveCount(0)
			await expect(page.getByText('path-style', { exact: true })).toHaveCount(0)
			await expect(page.getByText('tls-skip', { exact: true })).toHaveCount(2)
		}
		await page.screenshot({ path: testInfo.outputPath('profile-choices.png'), animations: 'disabled' })
		await page.getByRole('button', { name: /Use profile|^Use$/ }).click()
		await expect(page.getByRole('combobox', { name: 'Profile', exact: true })).toHaveValue('profiles-buckets-mobile-secondary')
		await activeTools.click()
		await page.getByRole('menuitem', { name: 'Edit' }).click()
		const edit = page.getByRole('dialog', { name: 'Edit Profile', exact: true })
		const tls = edit.locator('summary').filter({ hasText: 'TLS' })
		await expect(tls).toContainText('mTLS enabled')
		await expect(tls).not.toContainText('Off')
		await tls.scrollIntoViewIfNeeded()
		await edit.screenshot({ path: testInfo.outputPath('saved-tls-summary.png'), animations: 'disabled' })
	})

	test(`finished transfer metrics and clear scope stay accurate at ${width}px`, async ({ page }, testInfo) => {
		await page.setViewportSize({ width, height: 900 })
		await installJobsMobileResponsiveFixtures(page)
		await seedJobsMobileResponsiveStorage(page)
		await seedLocalStorage(page, { themeMode })
		await page.addInitScript(() => {
			const task = { profileId: 'jobs-mobile-profile', bucket: 'jobs-mobile-bucket', label: 'finished.txt', status: 'failed', createdAtMs: 1, finishedAtMs: Date.now(), loadedBytes: 4096, totalBytes: 8192, speedBps: 524288, etaSeconds: 30, error: 'Synthetic transfer failure.' }
			sessionStorage.setItem('transfersHistoryV1', JSON.stringify({ version: 1, savedAtMs: Date.now(), downloads: [{ ...task, id: 'download-stale', kind: 'object', key: 'finished.txt' }], uploads: [{ ...task, id: 'upload-hidden', prefix: '', fileCount: 1 }, { ...task, id: 'upload-done', label: 'done.csv', status: 'succeeded', error: undefined, loadedBytes: 8192, prefix: '', fileCount: 1 }] }))
		})
		await gotoJobsPage(page)
		await page.getByRole('button', { name: 'Transfers', exact: true }).click()
		const transfers = page.getByRole('dialog', { name: 'Transfers', exact: true })
		await expect(transfers.getByRole('listitem')).toContainText('4.00 KB/8.00 KB')
		await expect(transfers.getByRole('listitem')).not.toContainText('eta')
		await expect(transfers.getByRole('listitem')).not.toContainText('/s')
		await page.screenshot({ path: testInfo.outputPath('finished-transfer.png'), animations: 'disabled' })
		await transfers.getByRole('button', { name: /^Remove/ }).click()
		await expect(transfers.getByText('No downloads yet', { exact: true })).toBeVisible()
		const clear = transfers.getByRole('button', { name: 'Clear all finished', exact: true })
		await expect(clear).toBeVisible()
		await page.screenshot({ path: testInfo.outputPath('clear-hidden-upload.png'), animations: 'disabled' })
		await transfers.getByRole('tab', { name: /Uploads/ }).click()
		await expect(transfers.getByRole('button', { name: 'Clear done', exact: true })).toBeInViewport({ ratio: 1 })
		await expect(clear).toBeInViewport({ ratio: 1 })
		await page.screenshot({ path: testInfo.outputPath('clear-both-actions.png'), animations: 'disabled' })
		await transfers.getByRole('tab', { name: /Downloads/ }).click()
		await clear.click()
		await transfers.getByRole('tab', { name: /Uploads/ }).click()
		await expect(transfers.getByText('No uploads yet', { exact: true })).toBeVisible()
	})
}

for (const mode of ['list', 'grid'] as const) {
	test(`nested ${mode} results keep parent navigation and filter recovery`, async ({ page }, testInfo) => {
		await page.setViewportSize({ width: 390, height: 900 })
		await installObjectsMobileResponsiveFixtures(page)
		await seedObjectsMobileResponsiveStorage(page)
		await page.route('**/api/v1/buckets/objects-mobile-bucket/objects?**', async route => {
			const url = new URL(route.request().url())
			if (url.searchParams.get('prefix') !== 'reports/') return route.fallback()
			await route.fulfill({ json: buildObjectsListFixture({ bucket: 'objects-mobile-bucket', prefix: 'reports/', items: [{ key: 'reports/annual.csv', size: 4096, lastModified: '2024-01-01T00:00:00Z' }] }) })
		})
		await gotoObjectsPage(page)
		await page.getByRole('button', { name: 'Open prefix reports/', exact: true }).click()
		await expect(page.getByText('annual.csv', { exact: true })).toBeVisible()
		if (mode === 'grid') await page.getByRole('button', { name: /Grid/ }).click()
		await page.getByRole('button', { name: /Filters/ }).click()
		const filters = page.getByRole('dialog', { name: 'View options', exact: true })
		await filters.getByLabel('Type filter', { exact: true }).selectOption('files')
		await filters.getByLabel('Extension filter', { exact: true }).fill('no-match')
		await filters.getByRole('button', { name: 'Done', exact: true }).click()
		await expect(page.getByText('No results', { exact: true })).toBeVisible()
		await expect(page.getByRole('button', { name: 'Open parent folder', exact: true })).toBeVisible()
		await page.screenshot({ path: testInfo.outputPath(`nested-${mode}-no-results.png`), animations: 'disabled' })
		await page.getByRole('button', { name: 'Reset view', exact: true }).click()
		await expect(page.getByRole('button', { name: 'Select object annual.csv', exact: true })).toBeVisible()
		await page.getByRole('button', { name: 'Open parent folder', exact: true }).click()
		await expect(page.getByRole('button', { name: 'Select object alpha.txt', exact: true })).toBeVisible()
	})
}
